# 工作列拿來認「這個視窗屬於哪支程式」的身分(見 `winui.set_app_user_model_id`)。
# ⚠️ **與另外兩支刻意不同**:同一個字串會讓它們在工作列上併成一顆按鈕。
# ⚠️ **`scripts/make_shortcut.py` 會讀走這個值寫進 .lnk,兩邊必須同值**——那顆
# 捷徑正是工作列拿圖示的地方;不同值的話,釘選到工作列的那顆與執行中的視窗會
# 變成兩個各自獨立的按鈕。
APP_ID = "VincentLiang.MeetingScribe"

# 視窗標題列那一行 = **對使用者顯示的名稱**。
# ⚠️ **它與 `APP_DIR_NAME` 刻意不同值,也不可以合併成一份**:這一個純顯示,那一個
# 是落地位置(改了等於叫使用者重下 2-3 GB 的模型)。合併之後改標題就會順手把快取
# 搬家——模型還在磁碟上、程式卻說沒有,而兩個位置都存在,連「檔案不見了」都不會
# 發生。
APP_TITLE = "AI 文件.MD 轉換器"

# 視窗第一句:這支程式是做什麼的(標題列寫的是名字,名字說不出它做什麼)。
APP_SUB = "把會議錄音與各種文件,在這台電腦上轉成繁體中文的 Markdown。"

# 滑鼠停在**桌面圖示**上會看到的那句(`scripts/make_shortcut.py` 寫進 .lnk)。
# ⚠️ **與 `APP_SUB` 講同一件事卻刻意分成兩句**:讀到它的時機不同——這一句是在
# **程式還沒開起來**的時候被讀到的,桌面上一顆圖示旁邊沒有別的畫面,所以它得把
# 「會不會上傳」直接講完(那是這裡最常被問的第一個問題,而隱私是硬性規格)。
# `APP_SUB` 坐在視窗裡,底下就是整組本機跑的控制項,不必再解釋一次。
# ⚠️ 代價是**改了用途說明要記得改兩句**:沒有測試守得住「兩句話的意思一致」,
# 只守得住「兩句都在、都不是空的」。
APP_DESC = "把會議錄音與文件轉成繁體中文的 Markdown(全程在這台電腦上跑,不會上傳)"

# 這支工具在 `%LOCALAPPDATA%` 底下的資料夾名(AI 模型、命名進度、錄音工作目錄
# 都掛在它底下,見 `paths.appdata_root`)。
# ⚠️ **改它等於要使用者重新下載 2-3 GB 的模型**,所以它實際上是個對外承諾;而且
# 它同時是**錄音的工作目錄**,而錄音不能重來。與 `APP_TITLE` 的區分見上面那段。
APP_DIR_NAME = "meeting-scribe"

# 這支 app 的環境變數前綴。⚠️ **三支 app 在同一台機器上不可以同前綴**:那幾個
# 變數的用途正是「把落地位置導開」(測試導進 tmp、使用者覆寫佈景),同前綴等於
# 互相覆寫。
ENV_PREFIX = "MEETING_SCRIBE"
