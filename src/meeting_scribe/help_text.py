def help_pages(device_name: str, max_speakers: int) -> list[HelpPage]:
    """回傳目錄順序的說明篇章,最後一篇是「全部內容」。

    device_name:啟動時偵測到的執行裝置顯示名(app.DEVICE_NAMES 對照後);
    max_speakers:講者人數上限(app.MAX_SPEAKERS)。

    「全部內容」是把前面每一篇原樣接起來(使用者 2026-08-08 選定):
    切成一篇一篇之後,瀏覽器的 Ctrl+F 只搜得到當下顯示的那一篇——那是
    改版唯一失去的東西,而這一項零成本就補得回來(只是同一批字串換個
    接法,不新增任何元件)。截圖的位置由**唯一那一篇有圖的**決定,
    所以這裡不必知道是哪一篇。
    """
    pages = [
        HelpPage(START, _start()),
        HelpPage(RECORD, _record()),
        HelpPage(CONVERT, _convert()),
        HelpPage(NAMING, _naming()),
        HelpPage(DOCS, _docs()),
        HelpPage(TO_AI, _to_ai_top(), image=True, bottom=_to_ai_bottom()),
        HelpPage(TUNING, _tuning(device_name, max_speakers)),
        HelpPage(AUTOMATION, _automation()),
        HelpPage(TROUBLE, _trouble()),
    ]
    cut = next(i for i, p in enumerate(pages) if p.image)
    everything = HelpPage(
        EVERYTHING,
        "\n\n".join([p.top for p in pages[:cut]] + [pages[cut].top]),
        image=True,
        bottom="\n\n".join([pages[cut].bottom] + [p.top for p in pages[cut + 1:]]),
    )
    return [*pages, everything]
