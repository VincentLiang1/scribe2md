def contrast(fg: str, bg: str) -> float:
    """兩個色碼的 WCAG 對比度,1.0(同色)到 21.0(黑對白)。

    ⚠️ **公式住在這裡**,因為三個下游量的必須是同一條:MP4-2-SRT 的 GUI 測試原本
    自己有一支 `_contrast`,而兩份實作漂開的症狀是「同一個色碼在兩個 repo 量出不同
    的數字」——那時候沒有人分得出誰對。那一份 2026-09-03 收掉了,改呼叫這一支。
    ⚠️ **但本函式第一版的 docstring 就寫了「原本」,而提交的當下對面還沒收**——那句
    話進版時是假的,是下游的 session 查證時抓到的。教訓:**共用包這一半不可以替下游
    宣告一個還沒發生的狀態**,「已經收掉了」要等對面真的收了才寫得。
    ⚠️ 它**刻意不 import**(連 `re` 都不要),整份 `palette` 的前提就是
    「產生器與執行期都拿得到、不帶相依」。

    ⚠️ **這支不帶門檻,門檻由呼叫端決定。** `MUTED_MIN_CONTRAST`(9)只管 `muted`
    那一個鍵——中文小字反鋸齒淡一階是靠拉高門檻吸收的。⚠️ **不要拿它當全介面的門檻**:
    一般文字照 WCAG AA 的 4.5 就夠(MP4-2-SRT 線框鈕那條測試就是 4.5,藍字與白字都是
    一般文字),而**挑錯門檻的那一次不會報錯**,只會讓畫面莫名其妙變暗或漏掉真的太淡。

    ⚠️ 這是**照色碼算**的,不是螢幕取樣。中文小字反鋸齒之後實際渲染得比色碼淡
    一階,那一階的差距是靠 `MUTED_MIN_CONTRAST` 訂在 9(而不是 4.5)吸收掉的,
    不是靠這支函式修正——NotebookLM_OCR 2026-08-29 拿截圖量過,筆畫核心正好等於
    色碼本身((56,62,69) = #383e45),所以兩者對得起來。
    """
    def _lum(code: str) -> float:
        h = code.lstrip("#")
        if len(h) != 6:
            raise ValueError(f"色碼要是 #rrggbb 六碼:{code!r}")
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        r, g, b = (c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4
                   for c in (r, g, b))
        # ⚠️ 最後這一行要**逐項對得起 WCAG 規格書**,不要改寫回「(位移, 權重)」那種迴圈:
        # 這支是三個 repo 唯一信任的公式,而複驗它的人是拿規格書一項一項比的——迴圈版
        # 要先在腦裡把 0/2/4 映射回 R/G/B。⚠️ 這個 repo 才剛為「一個沒人複驗的數字抄了
        # 三代」付過代價,別讓公式本身變成下一個。
        return 0.2126 * r + 0.7152 * g + 0.0722 * b

    a, b = _lum(fg), _lum(bg)
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def muted_fits(surface: str) -> bool:
    """`muted` 坐在這一階底色上,**兩個模式都**過得了 `MUTED_MIN_CONTRAST` 嗎?

    ⚠️ **這支存在的理由是「鍵的名字會騙人」**(2026-09-03 補):`muted` 讀起來就是
    「次要文字色」,於是下一個做元件的人會照名字直覺挑它——而它只在**三階底色**上
    校準過。meeting-scribe 的網頁版與 meeting-scribe-native 的 `Seg.TLabel` 已經各自
    這樣選過一次,兩次都選到 `btn`、兩次都過不了各自的門檻。⚠️ 兩個獨立實作撞同一格
    不像巧合,**那是 API 的形狀在誘導**:原本的 `MUTED_SURFACES` 只說了「這三階可以」,
    沒說「其他的不行」,剩下的全是第三種狀態——**沒禁止、也沒保證**。這支把它變成
    問得到的:選底色之前先問一句。

    ⚠️ **一定要兩個模式都過才算數**,因為樣式只宣告一次、兩個模式共用同一份表
    (下游是 `background=pal[bg]` 這樣套的)。⚠️ 而**通過與否真的會分模式**:`trough`
    深色 11.20 過、淺色只有 8.85;`btn_lo` 深色 9.94 過、淺色只有 6.97。所以「我開起來
    看沒問題」本身就會騙人——他很可能只看了一個模式。

    ⚠️ 這支**不做決定、只報事實**。`muted_fits("btn")` 回 False 不代表「btn 該被修好」,
    要不要收、怎麼收(加專屬鍵,或讓那幾格改坐 `card`)是使用者的取捨——⚠️ 而**壓深
    `muted` 那條路已經算過、是死的**:要在 `btn` 上過 9,與 `ink` 的間距上限是 1.53
    (淺)與 1.16(深),都低於「次要文字要分得出正文」的下限 1.56,任何顏色都不行。
    """
    missing = [m for m in PALETTES if surface not in PALETTES[m]]
    if missing:
        raise ValueError(f"{surface!r} 不是色票裡的鍵(這幾個模式沒有:{missing})")
    return all(
        contrast(pal["muted"], pal[surface]) >= MUTED_MIN_CONTRAST
        for pal in PALETTES.values()
    )
